#!/usr/bin/env python3
"""Check a loaded copy against the load plan, and the plan's rows against their saved sources.

    python research/tools/load_verify.py readback DIR [--db EXPORT]        # write DIR/readback.sql
    python research/tools/load_verify.py copy (--from DIR | --loaded DB) --snapshot SNAP --offices FILE [--db EXPORT]
    python research/tools/load_verify.py sources --snapshot SNAP --offices FILE [--db EXPORT]
    python research/tools/load_verify.py --selfcheck

The rows checked are the ones promote_plan.build makes the load file from, so a row production
refuses, already states or holds for a decision is not expected in the copy.

readback writes one psql script for the read-only check login on the hosted copy: every table the
load writes, one JSON row per line, read exactly as the export is read, plus row counts. Run it
from DIR with the password typed at the prompt, after each load run; the second run's counts.txt
must equal the first's.

copy compares every planned row with the copy by primary key and every carried column.

sources reads each planned row that a report rests on back to the saved file it came from:
requirements (one need per source key, the forecast rows a title hash once merged), offices
(what each match rests on, and that each created office has a source and a parent the load
knows) and dated role claims (a notice contact's date and name against the saved notice, a
leadership date against the organization memory that states it, and a person a saved page names
against that page and the date it writes).
"""

